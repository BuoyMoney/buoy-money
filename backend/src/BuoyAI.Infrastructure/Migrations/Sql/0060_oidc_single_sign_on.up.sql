-- Single sign-on (OpenID Connect) for self-hosted servers, for example Pocket ID.
-- user_external_logins: which provider account (issuer + subject) belongs to which user, so a later
-- sign-in still matches after the person changes their email at the provider.
CREATE TABLE IF NOT EXISTS public.user_external_logins (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    user_id integer NOT NULL,
    issuer text NOT NULL,
    subject text NOT NULL,
    email text NULL,
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_login_at timestamp with time zone NULL,
    CONSTRAINT pk_user_external_logins PRIMARY KEY (id),
    CONSTRAINT fk_user_external_logins_user FOREIGN KEY (user_id) REFERENCES public."Users"("Id") ON DELETE CASCADE
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_user_external_logins_issuer_subject ON public.user_external_logins (issuer, subject);
CREATE INDEX IF NOT EXISTS ix_user_external_logins_user_id ON public.user_external_logins (user_id);

-- oidc_login_requests: short-lived steps of one sign-in round trip (state for the provider, then a
-- 60-second one-time code for the app). Only hashes of the secrets are stored; a row is deleted when used.
CREATE TABLE IF NOT EXISTS public.oidc_login_requests (
    id uuid NOT NULL,
    kind text NOT NULL,
    secret_hash text NOT NULL,
    platform text NOT NULL,
    nonce text NULL,
    code_verifier text NULL,
    return_path text NULL,
    invite_code text NULL,
    client_challenge text NULL,
    user_id integer NULL,
    is_new_user boolean NOT NULL DEFAULT false,
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at timestamp with time zone NOT NULL,
    CONSTRAINT pk_oidc_login_requests PRIMARY KEY (id)
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_oidc_login_requests_secret_hash ON public.oidc_login_requests (secret_hash);
CREATE INDEX IF NOT EXISTS ix_oidc_login_requests_expires_at ON public.oidc_login_requests (expires_at);
