-- Marketing lead capture: emails traded for an extended free trial on the marketing site.
--
-- One row per normalized email. Repeat submissions of the same address bump capture_count
-- rather than inserting again, so a visitor who fills the popup twice is not double-counted
-- and cannot stack offers.
--
-- offered_trial_days is snapshotted at capture time: changing the configured offer later
-- must never shorten what a visitor was already promised.
--
-- redeemed_at is set when the address registers and the longer trial is actually granted.
-- It is the idempotency guard: an offer is honoured exactly once.
--
-- snake_case to match 0019-0021; DbUp owns the schema, the EF mapping just agrees with it.
-- Idempotent: CREATE TABLE / INDEX IF NOT EXISTS are no-ops if they already exist.
BEGIN;

CREATE TABLE IF NOT EXISTS public.marketing_leads (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    -- Normalized (trimmed + lowercased) address. 320 = RFC-max local@domain.
    email character varying(320) NOT NULL,
    -- 'popup_timed' | 'popup_exit' | 'calculator_exit'
    source character varying(40) NULL,
    offered_trial_days integer NOT NULL,
    redeemed_at timestamp with time zone NULL,
    redeemed_by_user_id integer NULL,
    -- Calculator inputs/results as JSON when captured from the calculator prompt.
    calculator_snapshot text NULL,
    confirmation_sent_at timestamp with time zone NULL,
    capture_count integer NOT NULL DEFAULT 1,
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_marketing_leads PRIMARY KEY (id)
);

-- The lookup done on every registration, and the upsert conflict target.
CREATE UNIQUE INDEX IF NOT EXISTS ux_marketing_leads_email
    ON public.marketing_leads (email);

-- Partial index: the registration path only ever asks for UNREDEEMED offers, and in a
-- healthy funnel most rows are eventually redeemed.
CREATE INDEX IF NOT EXISTS ix_marketing_leads_unredeemed
    ON public.marketing_leads (email)
    WHERE redeemed_at IS NULL;

-- Retry target for the confirmation email.
CREATE INDEX IF NOT EXISTS ix_marketing_leads_confirmation_pending
    ON public.marketing_leads (created_at)
    WHERE confirmation_sent_at IS NULL;

COMMIT;
