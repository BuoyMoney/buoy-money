-- Push notifications (#190) — FCM device tokens, per-user push preferences, and a
-- quiet-hours deferral queue.
--   user_device_tokens        — one row per (user, FCM registration token). Tokens are
--                               upserted on login/app-start/refresh and pruned on FCM
--                               "Unregistered" send errors or 270 days of silence.
--   user_push_preferences     — master toggle + per-category toggles + quiet hours.
--                               Absent row = defaults (everything on, no quiet hours).
--   queued_push_notifications — pushes held during a user's quiet hours; a background
--                               sweeper delivers them once deliver_after passes.
-- snake_case to match 0019/0020; DbUp owns the schema, the EF mappings just agree with it.
-- Idempotent: CREATE TABLE / INDEX IF NOT EXISTS are no-ops if they already exist.
BEGIN;

CREATE TABLE IF NOT EXISTS public.user_device_tokens (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    user_id integer NOT NULL,
    -- FCM registration token; unique across users — a token identifies one app install,
    -- so re-registering under a different user re-parents the row.
    token text NOT NULL,
    -- 'android' | 'ios'
    platform text NOT NULL,
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_seen_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_user_device_tokens PRIMARY KEY (id)
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_user_device_tokens_token
    ON public.user_device_tokens (token);
CREATE INDEX IF NOT EXISTS ix_user_device_tokens_user_id
    ON public.user_device_tokens (user_id);

CREATE TABLE IF NOT EXISTS public.user_push_preferences (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    user_id integer NOT NULL,
    push_enabled boolean NOT NULL DEFAULT true,
    -- Category toggles: each gates the notification Types listed in
    -- PushNotificationService.CategoryForType. Unmapped types follow push_enabled only.
    connection_issues boolean NOT NULL DEFAULT true,
    budget_alerts boolean NOT NULL DEFAULT true,
    bill_reminders boolean NOT NULL DEFAULT true,
    subscription_detection boolean NOT NULL DEFAULT true,
    transaction_review boolean NOT NULL DEFAULT true,
    -- Quiet hours, minutes-from-midnight in the user's LOCAL time (start may be > end,
    -- meaning the window wraps past midnight, e.g. 22:00 → 07:00).
    quiet_hours_enabled boolean NOT NULL DEFAULT false,
    quiet_hours_start_minutes integer NOT NULL DEFAULT 1320,
    quiet_hours_end_minutes integer NOT NULL DEFAULT 420,
    -- The device's UTC offset at last prefs write / device registration. Refreshed often
    -- enough (every app start) that DST drift self-heals within a day.
    time_zone_offset_minutes integer NOT NULL DEFAULT 0,
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_user_push_preferences PRIMARY KEY (id)
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_user_push_preferences_user_id
    ON public.user_push_preferences (user_id);

CREATE TABLE IF NOT EXISTS public.queued_push_notifications (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    user_id integer NOT NULL,
    title text NOT NULL,
    body text NOT NULL,
    -- JSON object of FCM data fields (route, notificationId, type).
    data_json text NOT NULL,
    deliver_after timestamp with time zone NOT NULL,
    attempts integer NOT NULL DEFAULT 0,
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_queued_push_notifications PRIMARY KEY (id)
);

-- The sweeper polls "due" rows.
CREATE INDEX IF NOT EXISTS ix_queued_push_notifications_deliver_after
    ON public.queued_push_notifications (deliver_after);

COMMIT;
