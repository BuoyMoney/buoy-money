-- 0001  Admin broadcast / incident email (#552)
--   * ProductAnnouncements opt-out preference (default ON) on user_email_preferences
--   * Durable Broadcasts job table + per-recipient BroadcastRecipients table
BEGIN;

-- Default-on opt-out: existing users keep receiving product announcements unless they opt out.
ALTER TABLE public.user_email_preferences
    ADD COLUMN "ProductAnnouncements" boolean NOT NULL DEFAULT true;

CREATE TABLE public."Broadcasts" (
    "Id"                uuid NOT NULL,
    "Subject"           character varying(300) NOT NULL,
    "BodyMarkdown"      text NOT NULL,
    "BodyHtml"          text NOT NULL,
    "Category"          integer NOT NULL,
    "Audience"          integer NOT NULL,
    "Status"            integer NOT NULL,
    "TotalRecipients"   integer NOT NULL,
    "SentCount"         integer NOT NULL,
    "FailedCount"       integer NOT NULL,
    "SkippedCount"      integer NOT NULL,
    "CreatedByUserId"   integer NOT NULL,
    "CreatedByUsername" character varying(256),
    "IdempotencyKey"    character varying(128) NOT NULL,
    "CreatedAt"         timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "StartedAt"         timestamp with time zone,
    "CompletedAt"       timestamp with time zone,
    "Error"             text,
    CONSTRAINT "PK_Broadcasts" PRIMARY KEY ("Id")
);

CREATE UNIQUE INDEX "IX_Broadcasts_IdempotencyKey" ON public."Broadcasts" ("IdempotencyKey");
CREATE INDEX "IX_Broadcasts_Status" ON public."Broadcasts" ("Status");

CREATE TABLE public."BroadcastRecipients" (
    "Id"          bigint GENERATED BY DEFAULT AS IDENTITY,
    "BroadcastId" uuid NOT NULL,
    "UserId"      integer NOT NULL,
    "Email"       character varying(256) NOT NULL,
    "Status"      integer NOT NULL,
    "Error"       text,
    "SentAt"      timestamp with time zone,
    CONSTRAINT "PK_BroadcastRecipients" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_BroadcastRecipients_Broadcasts_BroadcastId"
        FOREIGN KEY ("BroadcastId") REFERENCES public."Broadcasts" ("Id") ON DELETE CASCADE
);

CREATE INDEX "IX_BroadcastRecipients_BroadcastId_Status"
    ON public."BroadcastRecipients" ("BroadcastId", "Status");
CREATE UNIQUE INDEX "IX_BroadcastRecipients_BroadcastId_UserId"
    ON public."BroadcastRecipients" ("BroadcastId", "UserId");

COMMIT;
